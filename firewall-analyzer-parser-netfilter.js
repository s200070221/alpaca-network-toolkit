// ══════════════════════════════════════════════════════════
//  LINUX NETFILTER PARSER（iptables-save／nft list ruleset，2026-10-02 新增，第十輪發想 ZB）
// ══════════════════════════════════════════════════════════
// 格式以本機實際執行 iptables v1.8.10 的 iptables-save／ip6tables-save 與 nftables v1.0.9 的 nft list ruleset
// 輸出確認（在獨立網路命名空間建立規則後匯出），範例檔 test_config/netfilter_*.{txt,conf} 即為原始輸出：
// - iptables-save：*filter／*nat 等表格段落，:CHAIN POLICY [計數] 宣告鏈，-A CHAIN 選項… -j 目標，COMMIT 結束；
//   選項順序固定為 -s -d -i -o -p，再接 -m 模組（tcp --dport、multiport --dports、conntrack --ctstate、
//   state --state、comment --comment、set --match-set）；! 放在選項前表示反向
// - nft：table 家族 名稱 { set 名稱 { elements = { … } } chain 名稱 { type filter hook X priority …; policy …; 規則… } }，
//   規則為 iifname／oifname、ip|ip6 saddr|daddr [!=] 值|@集合|{ 清單 }、tcp|udp dport 值|{ 清單 }|a-b、
//   ct state a,b，結尾 accept／drop／reject／jump X，comment "…"
// 對應方式比照 VyOS：INPUT／input 鏈目的介面為 local、OUTPUT 來源為 local；jump 規則本身不列出，
// 跳入的自訂鏈規則以 jump 規則的進入介面作為來源介面；LOG／log 這類非終止規則不列為規則。
// 鏈的預設政策（policy drop）不列成規則（比照 EdgeRouter／VyOS）
const NetfilterParser = (() => {
  const isNft = t => /^\s*table\s+(?:ip|ip6|inet|arp|bridge|netdev)\s+\S+\s*\{/m.test(t);
  const isIptables = t => /^\*(?:filter|nat|mangle|raw)\s*$/m.test(t) && /^-A\s+\S+/m.test(t);
  const deq = s => String(s || '').replace(/^"(.*)"$/, '$1');

  function hookOf(chain) { const c = chain.toLowerCase(); return ['input', 'forward', 'output', 'prerouting', 'postrouting'].includes(c) ? c : ''; }
  function pol(id, o) {
    const sa = _splitAddr(o.src, o.addrTypeMap), da = _splitAddr(o.dst, o.addrTypeMap);
    return {
      id, name: o.comment || `${o.chain}-${o.num}`, srcIntf: o.srcIntf, dstIntf: o.dstIntf,
      srcAddr: o.src, dstAddr: o.dst, srcAddr4: sa.v4, srcAddr6: sa.v6, dstAddr4: da.v4, dstAddr6: da.v6,
      service: o.port ? `${o.proto || 'tcp'}/${o.port}` : (o.proto || 'all'), schedule: 'always',
      action: o.action === 'accept' ? 'accept' : 'deny', actionRaw: o.action,
      nat: 'disable', ippool: 'disable', poolname: '-', logtraffic: o.log ? 'all' : 'disable',
      utm: { av: '-', ips: '-', webfilter: '-', appctrl: '-' }, status: 'enable',
      users: '-', groups: '-', comments: o.comment || '', _vdom: '', connState: o.state || [], chain: o.chain, ruleNum: String(o.num), family: o.family,
      // 位址家族（2026-10-06，MC）：ip6tables／nft ip6 表為 v6、iptables／nft ip 表為 v4、nft inet 表兩者皆適用（不標）
      _family: o.family === 6 ? 'v6' : o.family === 4 ? 'v4' : undefined,
    };
  }
  // 規則 → 政策：先找出各自訂鏈被哪些介面的 jump 跳入，再逐條轉換
  // 自訂鏈只有一個 jump 來源時，鏈內規則未指定的條件（介面、位址、協定、埠）沿用 jump 規則的條件；
  // 多個來源時只合併進入介面（條件各不相同，無法合成單一規則）
  function buildPolicies(rules, addrTypeMap) {
    const jumps = {};
    rules.forEach(r => { if (r.action === 'jump' && r.target) (jumps[r.target] = jumps[r.target] || []).push(r); });
    const out = [];
    const counter = {};
    rules.forEach(r => {
      const ck = `${r.family}/${r.chain}`;
      counter[ck] = (counter[ck] || 0) + 1;
      if (!['accept', 'drop', 'reject'].includes(r.action)) return;
      const js = jumps[r.chain] || [];
      const j = js.length === 1 ? js[0] : {};
      const hook = r.hook || j.hook;
      out.push(pol(out.length + 1, {
        chain: r.family === 6 && !/6$/.test(r.chain) ? r.chain + '(v6)' : r.chain, num: counter[ck], comment: r.comment, family: r.family,
        srcIntf: r.inIf || j.inIf || [...new Set(js.map(x => x.inIf || 'any'))].join(',') || (hook === 'output' ? 'local' : '-'),
        dstIntf: r.outIf || j.outIf || (hook === 'input' ? 'local' : '-'),
        src: r.src || j.src || 'any', dst: r.dst || j.dst || 'any', proto: r.proto || j.proto, port: r.dport || j.dport,
        action: r.action === 'accept' ? 'accept' : r.action, log: r.log, state: r.state || j.state, addrTypeMap,
      }));
    });
    return out;
  }

  // ── iptables-save ─────────────────────────────────────────
  function tokenize(line) { return line.match(/"(?:[^"\\]|\\.)*"|\S+/g) || []; }
  function parseIptables(text) {
    const rules = [], nat = [], chains = {};
    let table = '', family = 4;
    for (const raw of text.split('\n')) {
      const line = raw.trim();
      const g = line.match(/^# Generated by (ip6?)tables-save/);
      if (g) { family = g[1] === 'ip6' ? 6 : 4; continue; }
      if (!line || line.startsWith('#')) continue;
      if (line.startsWith('*')) { table = line.slice(1); continue; }
      const c = line.match(/^:(\S+)\s+(\S+)/);
      if (c) { chains[`${table}/${c[1]}`] = c[2]; continue; }
      if (!line.startsWith('-A ')) continue;
      const t = tokenize(line);
      const r = { chain: t[1], table, family, hook: hookOf(t[1]) };
      let neg = false;
      for (let i = 2; i < t.length; i++) {
        const k = t[i], v = t[i + 1];
        if (k === '!') { neg = true; continue; }
        // 只貼了部分內容時，選項後面可能缺值（截斷的行），其餘選項照常處理
        if (v === undefined && /^-/.test(k)) break;
        const nv = x => (neg ? '!' : '') + x;
        if (k === '-s' || k === '--source') { r.src = nv(v.replace(/\/32$/, '')); i++; }
        else if (k === '-d' || k === '--destination') { r.dst = nv(v.replace(/\/32$/, '')); i++; }
        else if (k === '-i' || k === '--in-interface') { r.inIf = nv(v); i++; }
        else if (k === '-o' || k === '--out-interface') { r.outIf = nv(v); i++; }
        else if (k === '-p' || k === '--protocol') { r.proto = nv(v.toLowerCase()); i++; }
        else if (k === '--dport' || k === '--dports' || k === '--destination-port') { r.dport = nv(v.replace(/:/g, '-')); i++; }
        else if (k === '--ctstate' || k === '--state') { r.state = v.toLowerCase().split(','); i++; }
        else if (k === '--comment') { r.comment = deq(v); i++; }
        else if (k === '--match-set') { const dir = t[i + 2] || ''; if (/^dst/.test(dir)) r.dst = nv('@' + v); else r.src = nv('@' + v); i += 2; }
        else if (k === '-j' || k === '-g') { r.target = v; i++; }
        else if (k === '--to-destination') { r.toDst = v; i++; }
        else if (k === '--to-source') { r.toSrc = v; i++; }
        else if (k === '--log-prefix') { r.logPrefix = deq(v); i++; }
        neg = false;
      }
      const tg = (r.target || '').toUpperCase();
      if (table === 'nat') { r.natTarget = tg; nat.push(r); continue; }
      if (table !== 'filter') continue;
      r.action = tg === 'ACCEPT' ? 'accept' : tg === 'DROP' ? 'drop' : tg === 'REJECT' ? 'reject' : tg === 'LOG' ? 'log' : tg === 'RETURN' ? 'return' : 'jump';
      r.target = r.action === 'jump' ? r.target : '';
      rules.push(r);
    }
    // LOG 規則緊接著同條件的終止規則時（常見寫法：先 -j LOG 再 -j DROP），把記錄標到下一條規則
    rules.forEach((r, i) => {
      const n = rules[i + 1];
      if (r.action === 'log' && n && ['src', 'dst', 'inIf', 'outIf', 'proto', 'dport'].every(k => r[k] === n[k]) && n.chain === r.chain) n.log = true;
    });
    return { rules, nat: nat.map((r, i) => natRow(r, i)), chainPolicy: chains };
  }

  // ── nft list ruleset ──────────────────────────────────────
  function parseNft(text) {
    const rules = [], nat = [], sets = [];
    let table = null, chain = null, set = null, depth = 0, setBuf = '';
    for (const raw of text.split('\n')) {
      const line = raw.trim();
      if (!line || line.startsWith('#')) continue;
      let m;
      if ((m = line.match(/^table\s+(\S+)\s+(\S+)\s*\{$/))) { table = { family: m[1], name: m[2] }; depth = 1; continue; }
      if ((m = line.match(/^(?:set|map)\s+(\S+)\s*\{$/))) { set = { name: m[1], table: table && table.name }; setBuf = ''; continue; }
      if (set) {
        if (line === '}') { const el = setBuf.match(/elements\s*=\s*\{([^}]*)\}/); sets.push({ ...set, members: el ? el[1].split(',').map(x => x.trim()).filter(Boolean) : [] }); set = null; continue; }
        setBuf += ' ' + line; continue;
      }
      if ((m = line.match(/^chain\s+(\S+)\s*\{$/))) { chain = { name: m[1], hook: '', type: 'filter' }; continue; }
      if (line === '}') { if (chain) chain = null; else table = null; continue; }
      if (!chain) continue;
      if ((m = line.match(/^type\s+(\S+)\s+hook\s+(\S+)/))) { chain.type = m[1]; chain.hook = m[2]; continue; }
      if (/^policy\s/.test(line)) continue;
      const r = parseNftRule(line);
      r.chain = chain.name; r.hook = chain.hook; r.family = table && table.family === 'ip6' ? 6 : (table && table.family === 'ip' ? 4 : 0);
      if (chain.type === 'nat') { if (r.nat) nat.push(r); continue; }
      if (chain.type !== 'filter') continue;
      rules.push(r);
    }
    return { rules, nat: nat.map((r, i) => natRow(r, i)), sets };
  }
  // 單條 nft 規則：逐一比對已知運算式，其餘（counter、limit…）略過
  function parseNftRule(line) {
    const r = {};
    const listOrVal = s => s.replace(/^\{\s*|\s*\}$/g, '').split(/\s*,\s*/).join(',');
    const VAL = '(\\{[^}]*\\}|@\\S+|"[^"]*"|\\S+)';
    let m;
    if ((m = line.match(/\biifname\s+(!=\s*)?("[^"]*"|\S+)/) || line.match(/\biif\s+(!=\s*)?("[^"]*"|\S+)/))) r.inIf = (m[1] ? '!' : '') + deq(m[2]);
    if ((m = line.match(/\boifname\s+(!=\s*)?("[^"]*"|\S+)/) || line.match(/\boif\s+(!=\s*)?("[^"]*"|\S+)/))) r.outIf = (m[1] ? '!' : '') + deq(m[2]);
    if ((m = line.match(new RegExp('\\bip6?\\s+saddr\\s+(!=\\s*)?' + VAL)))) r.src = (m[1] ? '!' : '') + listOrVal(m[2]);
    if ((m = line.match(new RegExp('\\bip6?\\s+daddr\\s+(!=\\s*)?' + VAL)))) r.dst = (m[1] ? '!' : '') + listOrVal(m[2]);
    if ((m = line.match(new RegExp('\\b(tcp|udp|sctp|th)\\s+dport\\s+(!=\\s*)?' + VAL)))) { r.proto = m[1] === 'th' ? '' : m[1]; r.dport = (m[2] ? '!' : '') + listOrVal(m[3]); }
    if ((m = line.match(/\bmeta\s+l4proto\s+(\{[^}]*\}|\S+)/))) r.proto = listOrVal(m[1]);
    if (!r.proto && (m = line.match(/\bip\s+protocol\s+(\S+)/))) r.proto = m[1];
    if (/\bicmp\s+type\b/.test(line) && !r.proto) r.proto = 'icmp';
    if ((m = line.match(/\bct\s+state\s+(\S+)/))) r.state = m[1].split(',');
    if ((m = line.match(/\bcomment\s+"([^"]*)"/))) r.comment = m[1];
    r.log = /\blog\b/.test(line);
    if ((m = line.match(/\b(?:jump|goto)\s+(\S+)/))) { r.action = 'jump'; r.target = m[1]; }
    else if (/\baccept\b/.test(line)) r.action = 'accept';
    else if (/\bdrop\b/.test(line)) r.action = 'drop';
    else if (/\breject\b/.test(line)) r.action = 'reject';
    else if (/\breturn\b/.test(line)) r.action = 'return';
    else r.action = r.log ? 'log' : '';
    if ((m = line.match(/\bdnat\s+(?:ip6?\s+)?to\s+(\S+)/))) { r.nat = 'DNAT'; r.toDst = m[1]; }
    else if ((m = line.match(/\bsnat\s+(?:ip6?\s+)?to\s+(\S+)/))) { r.nat = 'SNAT'; r.toSrc = m[1]; }
    else if (/\bmasquerade\b/.test(line)) r.nat = 'MASQUERADE';
    else if ((m = line.match(/\bredirect\s+to\s+:?(\S+)/))) { r.nat = 'REDIRECT'; r.toDst = ':' + m[1]; }
    if (r.nat) r.natTarget = r.nat;
    return r;
  }

  // NAT 列：DNAT／REDIRECT → vip；SNAT／MASQUERADE → ippool
  function natRow(r, i) {
    const tg = r.natTarget;
    const status = 'enable', proto = r.proto || '-', comment = r.comment || '';
    if (tg === 'DNAT' || tg === 'REDIRECT') {
      const [ip, port] = String(r.toDst || '').split(/:(?=[^:]*$)/);
      return { type: 'vip', name: `DNAT-${i + 1}`, vipType: 'static', poolType: 'destination', extIp: r.dst || '-', mapIp: ip || '-',
        extIntf: r.inIf || '-', srcIntf: '-', startIp: '-', endIp: '-', portFwd: r.dport || port ? 'enable' : 'disable',
        extPort: r.dport || '-', mapPort: port || '-', proto, status, comment };
    }
    if (tg === 'SNAT' || tg === 'MASQUERADE') {
      return { type: 'ippool', name: `SNAT-${i + 1}`, vipType: 'overload', poolType: tg === 'MASQUERADE' ? 'masquerade' : 'source', extIp: r.src || '-',
        mapIp: tg === 'MASQUERADE' ? 'masquerade' : (r.toSrc || '-'), extIntf: r.outIf || '-', srcIntf: r.outIf || '-', startIp: '-', endIp: '-',
        portFwd: 'disable', extPort: '-', mapPort: '-', proto, status, comment };
    }
    return null;
  }

  function detect(text) { return isIptables(text) || isNft(text); }

  function parse(text) {
    text = String(text || '').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
    const nft = isNft(text);
    const res = nft ? parseNft(text) : parseIptables(text);
    const addresses = (res.sets || []).map(s => ({ category: 'address-group', name: '@' + s.name, type: 'group', subnet: '-', fqdn: '-', startIp: '-', endIp: '-',
      wildcard: '-', iface: '-', color: '0', comment: s.table ? `table ${s.table}` : '', members: s.members.join(', ') || '-', _vdom: '' }));
    const addrTypeMap = new Map(addresses.map(a => {
      const fams = new Set(a.members.split(/\s*,\s*/).filter(m => m && m !== '-').map(m => m.includes(':') ? 'v6' : 'v4'));
      return [a.name, fams.size > 1 ? 'mixed' : (fams.values().next().value || 'v4')];
    }));
    const ifNames = new Set();
    res.rules.forEach(r => { [r.inIf, r.outIf].forEach(i => { if (i && !/^[!@]/.test(i) && i !== 'lo') ifNames.add(i.replace(/^!/, '')); }); });
    (res.nat || []).forEach(n => { if (n) [n.extIntf, n.srcIntf].forEach(i => { if (i && i !== '-') ifNames.add(i); }); });
    // 設定檔只有規則，沒有介面位址；介面清單取自規則中出現的介面名稱
    const interfaces = [...ifNames].sort().map(n => ({ name: n, ip: '-', mask: '-', secondaryIps: [], type: 'physical', vlanId: '-', alias: n, desc: '', status: 'up',
      mtu: '-', speed: '-', mode: '-', vdom: '-', role: /wan|ppp|internet/i.test(n) ? 'WAN' : 'LAN', allowaccess: '-' }));
    return {
      vendor: 'Linux netfilter',
      deviceInfo: { vendor: 'Linux netfilter', hostname: '-', firmware: (text.match(/^# Generated by (ip6?tables-save v[\d.]+)/m) || [])[1] || (nft ? 'nftables' : '-'), model: '-', serial: '-', vdom: [] },
      interfaces, policies: buildPolicies(res.rules, addrTypeMap), routes: [], ha: null,
      nat: (res.nat || []).filter(Boolean), vpn: [], addresses, services: [], users: [], schedules: [],
      sdwan: { enabled: false, lbMode: '-', zones: [], members: [], healthChecks: [], services: [], neighbors: [] },
      dhcp: null, dns: null, snmp: null, logservers: null, wwan: null, wlan: null,
      _chainPolicy: res.chainPolicy || null,
    };
  }

  return { parse, detect, _parseNftRule: parseNftRule };
})();
